"""synthesizer.py - findings + the checker's notes -> the final memo (Section 5.10).
AWS edition: Bedrock via llm.parse(); findings are trimmed per task so a long run can't blow the
context; an education disclaimer is added in code, not left to the model."""
from __future__ import annotations

from deepsearch import llm
from deepsearch.common import ResearchReport, ValidationResult

SYNTH_PROMPT = """You are a senior equity research analyst.
Write an investment research memo using ONLY the findings provided.
- Quote numbers exactly as given, with units. Never invent a number. Write negatives with a plain ASCII "-".
- risk_factors: one bullet per material risk, each starting with the company name.
- key_metrics_table: a Markdown table, one row per company: revenue ($M), revenue growth (%),
  gross margin (%), operating margin (%), EPS ($), P/E, market cap.
- If data is missing, say so plainly.
- Mention every validation warning where it is relevant.
- sources: every URL that appears in the findings, and the metrics provider named in each metrics `source` field.
- If P/E or market cap is null, write "n/a" and do not estimate it.
- confidence_score (0 to 1) must reflect how complete and clean the data is."""

PER_TASK_CHARS = 6_000
DISCLAIMER = "Research summary generated by an AI agent for education; not investment advice."


async def synthesize_report(question: str, results: dict[int, str],
                            validation: ValidationResult) -> ResearchReport:
    findings = "\n\n".join(f"[Task {tid}]\n{text[:PER_TASK_CHARS]}" for tid, text in sorted(results.items()))
    notes = "\n".join(
        [f"WARNING: {w}" for w in validation.warnings]
        + [f"GAP: {g}" for g in validation.gaps]
        + [f"ERROR: {e}" for e in validation.errors]
    ) or "No issues found."
    report = await llm.parse(
        [{"role": "system", "content": SYNTH_PROMPT},
         {"role": "user", "content": f"QUESTION:\n{question}\n\nFINDINGS:\n{findings}\n\n"
                                     f"VALIDATION NOTES:\n{notes}"}],
        ResearchReport,
    )
    report.confidence_score = max(0.0, min(1.0, report.confidence_score))
    if not validation.is_valid:  # code, not the model, caps confidence on a failed check
        report.confidence_score = min(report.confidence_score, 0.5)
    if DISCLAIMER not in report.conclusion:
        report.conclusion = f"{report.conclusion}\n\n_{DISCLAIMER}_"
    return report


def to_markdown(r: ResearchReport) -> str:
    risks = "\n".join(f"- {x}" for x in r.risk_factors)
    sources = "\n".join(f"- {x}" for x in r.sources)
    return (f"# {r.title}\n\n**Confidence:** {r.confidence_score:.0%}\n\n## Executive summary\n"
            f"{r.executive_summary}\n\n## Key metrics\n{r.key_metrics_table}\n\n## Competitive analysis\n"
            f"{r.competitive_analysis}\n\n## Risk factors\n{risks}\n\n## Conclusion\n{r.conclusion}\n\n"
            f"## Sources\n{sources}\n")
